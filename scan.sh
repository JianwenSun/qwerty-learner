#!/bin/zsh

# 定义要扫描的目录（默认是 ~/Documents，可根据需要修改）
TARGET_DIR="$HOME/Documents"

# 输出标题
echo "============================================="
echo "📊 扫描目录：$TARGET_DIR"
echo "⏰ 扫描时间：$(date)"
echo "============================================="
echo ""

# 1. 找出最大的 20 个文件（按大小降序）
echo "🔍 最大的 20 个文件："
echo "---------------------------------------------"
find "$TARGET_DIR" -type f -exec du -h {} + | sort -hr | head -20
echo ""

# 2. 找出最大的 15 个文件夹（按大小降序）
echo "📁 最大的 15 个文件夹："
echo "---------------------------------------------"
du -h -d 2 "$TARGET_DIR" | sort -hr | head -15
echo ""

# 3. 统计总占用空间
echo "📈 目录总占用："
du -sh "$TARGET_DIR"
echo "============================================="